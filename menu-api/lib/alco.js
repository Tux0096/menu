/**
 * Крепкий алкоголь продаёт отдельное юрлицо на своей кассе (ЕГАИС, акцизы). По названию раздела меню iiko
 * решается, на какую кассу уходит позиция, если в админке («Кассы») для раздела не выбрано вручную.
 */
// Ром — только отдельным словом (не «ромашковый чай»); вино — «вино», «вина», «винная карта», но не «винегрет»
// Функция, а не константа: .env загружается после импортов модулей (ESM)
export const alcoRegex = () => process.env.IIKO_ALCO_CATEGORIES
  || '(^|\\s)(вин[оаеы]?($|\\s)|вина|винн|крепк|алкогол|коктейл|настойк|наливк|виски|водк|коньяк|бренди|кальвадос|граппа|текил|мескал'
  + '|ром($|\\s)|джин|вермут|ликер|ликёр|самбук|абсент|биттер|аперитив|дижестив|игрист|шампан|просекко|портвейн|херес|саке|шот|глинтвейн)';

const NOT_ALCO = /безалког|молочн|детск/i;

/** Код кассы для раздела по правилам источников ({ code, split_regex }) — или null (кухонная касса). */
export function autoRoute(categoryName, splits) {
  const name = String(categoryName || '');
  if (NOT_ALCO.test(name)) return null;
  for (const sp of splits) {
    let re;
    try { re = new RegExp(sp.split_regex, 'i'); } catch { continue; }
    if (re.test(name)) return sp.code;
  }
  return null;
}
