/**
 * Название блюда для гостя из названия в iiko: без служебных приставок кассы («ЗАЛ», «Зал.»)
 * и пометок юрлица («(ИП)», «(ООО)»), кавычки — «ёлочки». Своё название задают в карточке админки.
 */
export const cleanMenuName = (name) => String(name || '')
  .replace(/^\s*зал[\s.:\-–—]+/i, '')
  .replace(/\s*\((ип|ооо)\)\s*$/i, '')
  .replace(/"([^"]+)"/g, '«$1»')
  .replace(/\s{2,}/g, ' ')
  .trim() || String(name || '').trim();

/** Ключ блюда по названию: без регистра, «ё», пробелов, знаков и служебных приставок — одно блюдо на разных точках */
export const menuKey = (name) => cleanMenuName(name).toLowerCase().replace(/ё/g, 'е')
  .replace(/[^a-zа-я0-9]+/g, ' ').trim();

/**
 * Ключ настроек раздела из админки: название без регистра и знаков. Разделы кухни и бара с одним названием
 * («Бизнес-ланч» и там, и там) настраиваются отдельно: у раздела бара (все блюда со второй кассы) ключ «название|bar».
 * Старые настройки по одному названию остаются за разделом кухни.
 */
export const categoryKey = (name, bar = false) => {
  const k = menuKey(name);
  return k && bar ? `${k}|bar` : k;
};
